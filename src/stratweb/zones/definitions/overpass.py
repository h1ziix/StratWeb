"""Zone set for de_overpass, revision cs2-1.41.7.1-d263aa1118fb.

Boundaries are derived from the radar asset itself rather than eyeballed:
the overview PNG is decoded, its walkable pixels are partitioned between the
callouts of the user's official reference by walkable-path distance, and each
zone is the traced outline of its share. Zones therefore stop at walls and
never cover void. Growth is capped so unnamed space stays unknown instead of
being absorbed by a neighbour.

Site and spawn footprints come from the markers baked into the radar (orange
site outlines, green T-spawn box) and are confirmed by the demo: the repeated
plant positions of match dba336bb fall inside both sites. CT Spawn is the
freeze-end cluster of that match; on this radar it lies inside the A-site
outline (Valve's own CTSpawn anchor does too), so it is kept as a smaller
same-priority zone that wins the overlap deterministically.
"""

